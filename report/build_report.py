def _wrap(text: str, width: int = 92) -> str:
    import textwrap

    lines = []
    for line in text.split("\n"):
        indent = len(line) - len(line.lstrip())
        lines.append(textwrap.fill(line, width, subsequent_indent=" " * (indent + 4)) if line.strip() else line)
    return "\n".join(lines)


def on_page(canvas, doc) -> None:
    if doc.page == 1:
        return
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(INK2)
    canvas.drawString(2 * cm, 1.2 * cm, "ReflexDebug: Debugger-Grounded Self-Healing Code Agent")
    canvas.drawRightString(A4[0] - 2 * cm, 1.2 * cm, f"Page {doc.page}")
    canvas.setStrokeColor(RULE)
    canvas.line(2 * cm, 1.55 * cm, A4[0] - 2 * cm, 1.55 * cm)
    canvas.restoreState()


