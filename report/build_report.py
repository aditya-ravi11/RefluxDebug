def run_unit_tests() -> tuple[int, int]:
    proc = subprocess.run([sys.executable, "-m", "pytest", "-q", "-p", "no:cacheprovider"], cwd=ROOT,
                          capture_output=True, text=True)
    passed = int(m.group(1)) if (m := re.search(r"(\d+) passed", proc.stdout)) else 0
    failed = int(m.group(1)) if (m := re.search(r"(\d+) failed", proc.stdout)) else 0
    return passed, failed


def reference_check() -> list[tuple[str, int, int]]:
    from reflexdebug.config import Settings
    from reflexdebug.sandbox import Sandbox

    sb = Sandbox(Settings())
    out = []
    for t in TASKS:
        r = sb.run_tests(REFERENCE[t["id"]], HIDDEN[t["id"]])
        out.append((t["id"], len(r.passed), r.total))
    return out


def run_demo():
    from reflexdebug import ReflexDebugAgent, Settings
    from reflexdebug.demo import DEMO_TASK, demo_llm
    from reflexdebug.memory import ReflexionMemory

    settings = Settings()
    settings.max_steps_per_trial = 3
    llm = demo_llm()
    mem = ReflexionMemory(Path(tempfile.mkdtemp()) / "m.json", llm)
    return ReflexDebugAgent(llm, settings, memory=mem).solve(DEMO_TASK)


def assertion_locals_rate(records: list[dict]) -> float:
    firsts = [r["failures"][0] for r in records if r["detected"] and r["failures"]]
    a = [f for f in firsts if f["category"] == "assertion"]
    return sum(f["locals_captured"] for f in a) / (len(a) or 1)


