def live_values(bench, bench_v2, audit, audit_v2) -> dict:
    vals: dict = {}
    if bench:
        by = {x["strategy"]: x for x in bench["summary"]}
        for key, strat in (("one", "one_shot"), ("tb", "traceback_loop"), ("rich", "rich_feedback"),
                           ("rd", "reflexdebug")):
            if strat in by:
                vals[f"{key}_hidden"] = pct(by[strat]["mean_hidden_pass_rate"])
                vals[f"{key}_solved"] = f"{by[strat]['solved']}/{by[strat]['tasks']}"
        if "reflexdebug" in by:
            vals["final_calls"] = f"{by['reflexdebug']['mean_llm_calls']:.1f}"
            vals["final_cost"] = f"{by['reflexdebug']['total_cost_usd']:.3f}"
    if bench_v2:
        by2 = {x["strategy"]: x for x in bench_v2["summary"]}
        if "reflexdebug" in by2:
            vals["v2_calls"] = f"{by2['reflexdebug']['mean_llm_calls']:.1f}"
            vals["v2_cost"] = f"{by2['reflexdebug']['total_cost_usd']:.3f}"
    for tag, au in (("final", audit), ("v2", audit_v2)):
        if au:
            su = au["summary"]
            vals[f"{tag}_consistent"] = str(su["specs_consistent_with_reference"])
            vals[f"{tag}_improved"] = f"{su['repair_improved']} of {su['runs']}"
    if audit:
        vals["triage_total"] = str(audit["summary"].get("triage_amendments", 0))
        vals["triage_just"] = str(audit["summary"].get("triage_justified", 0))
    return vals


