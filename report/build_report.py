def esc(text: str) -> str:
    return text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def P(text: str, style: str = "body") -> Paragraph:
    return Paragraph(text, S[style])


def bullets(items: list[str]) -> ListFlowable:
    return ListFlowable([ListItem(P(i), leftIndent=14) for i in items], bulletType="bullet", start="\u2022",
                        leftIndent=14, bulletFontName="Helvetica", bulletFontSize=9)


def table(rows: list[list], widths: list[float], header: bool = True) -> Table:
    data = [[c if not isinstance(c, str) else Paragraph(esc(c), S["cellb" if header and i == 0 else "cell"])
             for c in row] for i, row in enumerate(rows)]
    t = Table(data, colWidths=[w * cm for w in widths], repeatRows=1 if header else 0)
    style = [
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LINEBELOW", (0, 0), (-1, -1), 0.4, RULE),
        ("TOPPADDING", (0, 0), (-1, -1), 3.5),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 3.5),
        ("LEFTPADDING", (0, 0), (-1, -1), 4),
    ]
    if header:
        style += [("BACKGROUND", (0, 0), (-1, 0), SHADE), ("LINEBELOW", (0, 0), (-1, 0), 0.8, INK2)]
    t.setStyle(TableStyle(style))
    return t


def captioned(t: Table, caption: str) -> KeepTogether:
    return KeepTogether([t, P(caption, "caption")])


def figure(path: Path, width_cm: float, caption: str) -> KeepTogether:
    from reportlab.lib.utils import ImageReader

    iw, ih = ImageReader(str(path)).getSize()
    w = width_cm * cm
    return KeepTogether([Image(str(path), width=w, height=w * ih / iw), P(caption, "caption")])


def pct(x: float) -> str:
    return f"{x * 100:.1f}%"


