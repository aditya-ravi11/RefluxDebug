def behaviour_section(bench: dict) -> list:
    rows = [r for r in bench["rows"] if r["strategy"] == "reflexdebug"]
    if not rows:
        return []
    tools: dict = {}
    trials = guards = disputes = reviews = triaged = errors = 0
    for r in rows:
        ex = r.get("extra") or {}
        for k, v in (ex.get("tool_counts") or {}).items():
            tools[k] = tools.get(k, 0) + v
        trials += ex.get("trials") or 0
        guards += ex.get("loop_guard_triggers") or 0
        disputes += len(ex.get("disputes") or [])
        reviews += len(ex.get("spec_review") or [])
        triaged += len(ex.get("spec_triage") or [])
        errors += bool(r.get("error")) and "budget" not in (r.get("error") or "")
    total_actions = sum(tools.values()) or 1
    evidence = sum(tools.get(k, 0) for k in ("trace_test", "eval_at_crash", "run_snippet", "inspect_failure"))
    edits = sum(tools.get(k, 0) for k in ("apply_patch", "rewrite_code"))
    tool_rows = [["Tool", "Calls", "Share"]] + [[k, str(v), f"{v / total_actions:.0%}"]
                                                for k, v in sorted(tools.items(), key=lambda kv: -kv[1])]
    text = (f"Across the {len(rows)} tasks the full agent ran {trials} Reflexion trials in total "
            f"({trials / len(rows):.1f} per task) and took {sum(tools.values())} ReAct actions: {evidence} evidence "
            f"actions (trace, eval, probe, inspect) and {edits} edits. The spec review changed {reviews} synthesised "
            f"tests before any code was written and evidence-based triage amended {triaged} more after the first "
            f"draft ran. The loop guard fired {guards} times, the agent itself disputed {disputes} tests, and "
            f"{errors} runs ended with an infrastructure error.")
    return [P("Agent behaviour", "h2"), P(text),
            captioned(table(tool_rows, [5, 3, 3]), "Table 11. ReAct actions taken by the full agent (all tasks).")]


def history_section(bench: dict, versions: list[tuple[str, dict]]) -> list:
    """ReflexDebug across development versions, plus the baselines of each run for context."""
    def agg(data, strat, tasks=None):
        rs = [r for r in data["rows"] if r["strategy"] == strat and (tasks is None or r["task"] in tasks)]
        if not rs:
            return None
        return (len(rs), sum(r["hidden_solved"] for r in rs), sum(r["hidden_pass_rate"] for r in rs) / len(rs),
                sum(r["usage"]["llm_calls"] for r in rs) / len(rs))

    rows = [["ReflexDebug version", "Tasks", "Solved", "Hidden pass", "LLM calls"]]
    for label, data in versions:
        a = agg(data, "reflexdebug")
        if a:
            rows.append([label, str(a[0]), f"{a[1]}/{a[0]}", pct(a[2]), f"{a[3]:.1f}"])
    return [P("10.6 How the agent changed across versions", "h2"),
            P("Table 12 shows the full agent in each development version: v1 (before the tracer, stopped after eight "
              "complete tasks), v2 (tracer and trace-driven fixes, before evidence-based spec triage) and the final "
              "version. The three baseline arms in Table 9 come from the v2 run and were not re-run, because none of "
              "the later changes touch them. Each version ran once, so differences of one task are within the "
              "run-to-run variation of the model."),
            captioned(table(rows, [5.4, 2.2, 2.4, 3, 2.6]), "Table 12. The full agent across development versions.")]


def audit_section(audit: dict | None, audit_v2: dict | None) -> list:
    if not audit:
        return []
    a = audit["summary"]
    out = [P("10.7 Auditing the synthesised specifications", "h2"),
           P("Because the reference solutions are known to be correct, each synthesised specification can itself be "
             "tested: a spec test that the reference solution fails is a wrong test. We also ran each run's first "
             "draft and final code against the hidden tests to see whether the repair loop helped "
             "(benchmark/spec_audit.py, no LLM calls).")]
    rows = [["Measure", "v2 (review only)" if audit_v2 else "", "Final (review + triage)"]]

    def line(label, key, fmt=str):
        v2 = fmt(audit_v2["summary"].get(key, 0)) if audit_v2 else ""
        rows.append([label, v2, fmt(a.get(key, 0))])

    line("Runs with a spec", "runs", lambda v: str(v))
    line("Specs the reference passes completely", "specs_consistent_with_reference")
    line("Wrong spec tests (reference fails them)", "spec_tests_wrong")
    line("Wrong spec tests before triage", "spec_tests_wrong_before_amendments")
    line("Tests amended by triage", "triage_amendments")
    line("... of which the test really was wrong", "triage_justified")
    line("First drafts that solve the task", "first_draft_solved")
    line("Final code that solves the task", "final_solved")
    line("Mean hidden pass: first draft", "mean_first_draft_hidden", pct)
    line("Mean hidden pass: final code", "mean_final_hidden", pct)
    line("Runs where repair improved hidden pass", "repair_improved")
    line("Runs where repair lowered hidden pass", "repair_hurt")
    if not audit_v2:
        rows = [[r[0], r[2]] for r in rows]
    out.append(captioned(table(rows, [7.6, 4.2, 4.7] if audit_v2 else [9, 7.5]),
                         "Table 13. Specification audit against the reference solutions."))
    return out


